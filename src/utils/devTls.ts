import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

export interface TlsCredentials {
  cert: Buffer;
  key: Buffer;
  certPath: string;
  keyPath: string;
  autoGenerated: boolean;
}

/**
 * Loads TLS certificate and private key from `certPath` / `keyPath`.
 * In development/test environments, if the certificate files do not exist yet,
 * automatically generates a SAN-enabled X.509 self-signed certificate for
 * `localhost` and `127.0.0.1` via OpenSSL so `https://localhost:3443` works out of the box.
 */
export function ensureTlsCredentials(options: {
  certPath: string;
  keyPath: string;
  allowAutoGenerate: boolean;
}): TlsCredentials {
  const absCert = resolve(process.cwd(), options.certPath);
  const absKey = resolve(process.cwd(), options.keyPath);

  let autoGenerated = false;

  if (!existsSync(absCert) || !existsSync(absKey)) {
    if (!options.allowAutoGenerate) {
      throw new Error(
        `TLS certificate files missing in production mode: cert=${absCert}, key=${absKey}`
      );
    }

    mkdirSync(dirname(absCert), { recursive: true });
    mkdirSync(dirname(absKey), { recursive: true });

    execFileSync(
      "openssl",
      [
        "req",
        "-x509",
        "-newkey",
        "ec",
        "-pkeyopt",
        "ec_paramgen_curve:prime256v1",
        "-nodes",
        "-keyout",
        absKey,
        "-out",
        absCert,
        "-days",
        "365",
        "-subj",
        "/CN=localhost/O=Splittel MCP Dev",
        "-addext",
        "subjectAltName=DNS:localhost,IP:127.0.0.1",
      ],
      { stdio: "ignore" }
    );
    autoGenerated = true;
  }

  return {
    cert: readFileSync(absCert),
    key: readFileSync(absKey),
    certPath: absCert,
    keyPath: absKey,
    autoGenerated,
  };
}

