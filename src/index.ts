import https from "node:https";
import http from "node:http";
import { config } from "./config/env.js";
import { createSplittelRuntime } from "./app.js";
import { ensureTlsCredentials } from "./utils/devTls.js";

async function bootstrap(): Promise<void> {
  const runtime = await createSplittelRuntime(config);

  let server: https.Server | http.Server;
  let protocolLabel: "https" | "http";

  if (config.HTTPS_ENABLED) {
    const tls = ensureTlsCredentials({
      certPath: config.TLS_CERT_PATH,
      keyPath: config.TLS_KEY_PATH,
      allowAutoGenerate: config.NODE_ENV !== "production",
    });
    server = https.createServer({ cert: tls.cert, key: tls.key }, runtime.app);
    protocolLabel = "https";
    if (tls.autoGenerated) {
      console.info(
        `[@Splittel] Auto-generated local TLS certificate at ${tls.certPath}`
      );
    }
  } else {
    // Cloud Run / GKE Ingress mode where TLS 1.3 terminates at Google Front End
    server = http.createServer(runtime.app);
    protocolLabel = "http";
  }

  server.listen(config.PORT, config.HOST, () => {
    console.info(
      [
        `==================================================================`,
        `  @Splittel Remote MCP Server (Google Connected Apps Ready)`,
        `  Bind:          ${protocolLabel}://${config.HOST}:${config.PORT}`,
        `  Public Base:   ${config.PUBLIC_BASE_URL}`,
        `  MCP Endpoint:  ${config.PUBLIC_BASE_URL}/mcp (Streamable HTTP + SSE)`,
        `  SSE Endpoint:  ${config.PUBLIC_BASE_URL}/sse`,
        `  Bill Board UI: ${config.PUBLIC_BASE_URL}/ui/bill-board`,
        `  OAuth 2.1 PRM: ${config.PUBLIC_BASE_URL}/.well-known/oauth-protected-resource`,
        `  Storage:       ${runtime.store.getActiveDriver()}`,
        `  R2 Bucket:     ${runtime.r2Storage.isConfigured() ? config.R2_BUCKET_NAME : "disabled (transient memory)"}`,
        `  Gemini Vision: ${config.GEMINI_API_KEY.trim() ? "enabled (gemini-3.8-flash primary)" : "disabled (Tesseract LSTM only)"}`,
        `  Scan Limit:    ${config.RECEIPT_SCAN_RATE_LIMIT_MAX} scans/min`,
        `==================================================================`,
      ].join("\n")
    );
  });

  const gracefulShutdown = async (signal: string) => {
    console.info(`[@Splittel] Received ${signal}. Draining connections...`);
    server.close(async () => {
      await runtime.shutdown();
      process.exit(0);
    });
    setTimeout(() => process.exit(1), 10_000).unref();
  };

  process.on("SIGINT", () => void gracefulShutdown("SIGINT"));
  process.on("SIGTERM", () => void gracefulShutdown("SIGTERM"));
}

bootstrap().catch((err) => {
  console.error("[@Splittel] Fatal startup failure:", err);
  process.exit(1);
});

